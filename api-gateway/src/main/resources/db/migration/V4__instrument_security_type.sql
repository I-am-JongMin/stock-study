-- ============================================================================
-- V4 — 종목 상품 종류 (ADR-026)
--
-- **왜 필요한가**
-- 키움 ka10099 의 유가증권 응답에는 주식 910 건보다 ETF 가 1,192 건 더 많다.
-- 구분 없이 담으면 초성 검색(§F1.2)이 TIGER 시리즈로 뒤덮인다. 그렇다고 ETF 를
-- 버리면 나중에 넣을 때 컬럼 추가 + 전체 재동기화가 필요하다.
-- 마스터는 있는 그대로 담고, 걸러내는 일은 조회가 한다.
--
-- **왜 CHECK 로 값을 고정하는가**
-- 이 목록은 **우리의 어휘**이지 키움의 어휘가 아니다. 키움이 새 분류를 추가하면
-- 애플리케이션이 OTHER 로 떨어뜨리고 경고를 남기므로(하네스 G9 의 변환 지점),
-- 이 제약이 외부 변화 때문에 깨지는 일은 없다. 반대로 우리 코드가 오타난 값을
-- 넣으려 하면 여기서 죽는다 — 그것이 이 제약의 목적이다.
--
-- **왜 NOT NULL 을 한 번에 올리는가**
-- instrument 가 아직 비어 있다. 운영 데이터가 쌓인 뒤였다면 nullable 추가 →
-- 백필 → SET NOT NULL 3 단계가 필요하다 (V3 와 같은 판단).
--
-- **인덱스를 지금 만들지 않는 이유**
-- 조회 패턴이 아직 코드로 존재하지 않는다. KOSPI+KOSDAQ 전종목이 4,300 행
-- 남짓이라 순차 스캔도 밀리초 단위다. §3.3-4 초성 검색 API 를 쓰면서 실제
-- 실행계획을 보고 정한다 — 추측으로 인덱스를 늘리면 쓰기 비용만 남는다.
-- ============================================================================

ALTER TABLE instrument
    ADD COLUMN security_type VARCHAR(16) NOT NULL;

ALTER TABLE instrument
    ADD CONSTRAINT instrument_security_type_check
        CHECK (security_type IN ('STOCK', 'ETF', 'ETN', 'REIT', 'FUND', 'OTHER'));

COMMENT ON COLUMN instrument.security_type IS
    '우리가 정한 상품 종류. 키움 marketCode 를 애플리케이션이 매핑한다 (ADR-026)';
